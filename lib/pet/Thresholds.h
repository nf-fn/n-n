// 検出の閾値。
//
// 既定値はすべて test/fixtures/*.csv の実測から決めた。平滑化後 (tau 0.30s)
// の線形加速度 [g] と角速度 [deg/s] の p10〜p90 は次のとおりだった:
//
//   動作     線形加速度      角速度
//   idle     0.001-0.002     0.5
//   stroke   0.069-0.089     9.1-14.9
//   walk     0.091-0.225    27.6-55.2
//   shake    0.556-0.813    59.8-89.0
//   lift     0.067-0.476    15.6-118.7
//   tap      0.008-0.072     1.5-15.1  (背景は静かで、衝撃だけが鋭い)
//
// ただしこれは 1 人が 1 回録音しただけの値なので、触り方の癖には合わせて
// いない。キャリブレーションで各自の値に差し替えられるよう構造体に出す。
#pragma once

namespace pet {

struct Thresholds {
  // 静止と見なす上限。idle の 0.002 と stroke の 0.069 の間。
  float quietLin = 0.02f;

  // 撫で・手持ちと見なす線形加速度の下限。tap の裾 (0.072) を避けつつ
  // stroke の下限 (0.069) は拾いたいので、持続時間の条件と併用する。
  float contactMinLin = 0.045f;

  // 撫で・手持ちの上限。手持ちの上限 0.225 より上、振りの下限 0.556 より下。
  float contactMaxLin = 0.30f;

  // 撫でと手持ちを分ける角速度。ここが最も重要な境界。
  // 大きさでは重なる撫で (9-15) と手持ち (28-55) を、これだけで分離できる。
  float strokeMaxGyro = 20.0f;

  // 振りと見なす線形加速度の下限。
  float shakeMinLin = 0.30f;

  // つつきの 1 サンプル間の加速度変化 [g]。
  // tap の最大 2.03 に対し、shake 0.55 / stroke 0.28 / walk 0.95。
  float tapJerk = 0.80f;

  // つつきと認めるための背景の静けさ。
  // 衝撃時の線形加速度の中央値は tap 0.071 / lift 0.109 / walk 0.222 だった。
  float tapMaxBackground = 0.10f;

  // 持ち上げの上向き加速度。平滑化後の最大値は実測で
  // lift 0.59 / walk 0.28 / shake 0.19 / tap 0.03 / stroke 0.02 だった。
  float liftUpwardAccel = 0.35f;
};

}  // namespace pet
